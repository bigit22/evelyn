def build_resume_adapt_user_prompt(
    base_resume: str, vacancy_description: str, target_role: str | None = None
) -> str:
    role_part = f"\nЦЕЛЕВАЯ ДОЛЖНОСТЬ: {target_role}" if target_role else ""
    return f"""ИСХОДНОЕ РЕЗЮМЕ:
{base_resume}

ОПИСАНИЕ ВАКАНСИИ:
{vacancy_description}{role_part}

Адаптируй резюме под эту вакансию."""
